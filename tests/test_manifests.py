def test_secret_example_has_only_placeholders():
    secret = _one("secret.example.yaml", "Secret")
    assert secret["metadata"]["name"] == "kick-tts-secrets"
    data = secret["stringData"]
    assert set(data) == {
        "CONTROL_TOKEN", "OVERLAY_KEY", "ANTHROPIC_API_KEY",
        "KICK_CLIENT_ID", "KICK_CLIENT_SECRET", "KICK_BROADCASTER_USER_ID",
    }
    for key, value in data.items():
        assert value in ("CHANGE_ME", "0"), f"{key} must be a placeholder"
    assert data["KICK_BROADCASTER_USER_ID"] == "0"  # int setting: must stay parseable


def test_servicemonitor_targets_the_service():
    sm = _one("servicemonitor.yaml", "ServiceMonitor")
    svc = _one("service.yaml", "Service")
    assert sm["metadata"]["labels"]["release"] == "CHANGE_ME"
    assert sm["spec"]["selector"]["matchLabels"].items() <= svc["metadata"]["labels"].items()
    (endpoint,) = sm["spec"]["endpoints"]
    assert endpoint["port"] == "http"
    assert endpoint["path"] == "/metrics"
    assert endpoint["interval"] == "30s"
    text = (DEPLOY / "servicemonitor.yaml").read_text(encoding="utf-8")
    assert "serviceMonitorSelector" in text  # discovery command documented in the file


def test_cronjob():
    cj = _one("cronjob.yaml", "CronJob")
    assert cj["spec"]["schedule"] == "0 */6 * * *"
    assert cj["spec"]["concurrencyPolicy"] == "Forbid"
    pod = cj["spec"]["jobTemplate"]["spec"]["template"]["spec"]
    assert pod["securityContext"]["runAsNonRoot"] is True
    (c,) = pod["containers"]
    assert c["command"] == ["python", "scripts/kick_subscribe.py", "ensure"]
    assert c["image"] == _one("deployment.yaml", "Deployment")["spec"]["template"]["spec"]["containers"][0]["image"]
    assert any(e.get("secretRef", {}).get("name") == "kick-tts-secrets" for e in c["envFrom"])
    assert c["resources"]["limits"]["memory"] and c["resources"]["requests"]["cpu"]


