"""Static checks of the deploy artefacts (Dockerfile, deploy/*.yaml, docs/DEPLOY.md). Offline, no cluster needed."""
from __future__ import annotations

import re
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parent.parent
DEPLOY = ROOT / "deploy"


def _load(name: str) -> list[dict]:
    with (DEPLOY / name).open(encoding="utf-8") as fh:
        return [d for d in yaml.safe_load_all(fh) if d]


def _one(name: str, kind: str) -> dict:
    docs = [d for d in _load(name) if d.get("kind") == kind]
    assert len(docs) == 1, f"{name}: expected exactly one {kind}"
    return docs[0]


def _all_docs() -> list[dict]:
    docs: list[dict] = []
    for path in sorted(DEPLOY.glob("*.yaml")):
        docs.extend(_load(path.name))
    return docs


@pytest.fixture(scope="module")
def deployment() -> dict:
    return _one("deployment.yaml", "Deployment")


@pytest.fixture(scope="module")
def container(deployment) -> dict:
    containers = deployment["spec"]["template"]["spec"]["containers"]
    assert len(containers) == 1
    return containers[0]


def _env(container: dict) -> dict[str, str]:
    return {e["name"]: e["value"] for e in container["env"] if "value" in e}


def test_every_deploy_file_parses_and_has_a_kind():
    files = sorted(DEPLOY.glob("*.yaml"))
    names = {p.name for p in files}
    assert {
        "deployment.yaml", "service.yaml", "ingress.yaml", "pvc.yaml",
        "secret.example.yaml", "servicemonitor.yaml", "cronjob.yaml",
    } <= names
    for path in files:
        docs = _load(path.name)
        assert docs, f"{path.name} is empty"
        for doc in docs:
            assert doc.get("apiVersion") and doc.get("kind") and doc.get("metadata", {}).get("name")


def test_manifests_are_namespace_less():
    docs = _all_docs()
    assert docs
    for doc in docs:
        assert "namespace" not in doc["metadata"], f"{doc['kind']}/{doc['metadata']['name']} sets a namespace"
        # pod templates must not smuggle one in either
        template = doc.get("spec", {}).get("template", {}) or doc.get("spec", {}).get("jobTemplate", {})
        assert "namespace" not in template.get("metadata", {})


def test_no_pronounce_configmap_is_committed():
    assert not [d for d in _all_docs() if d["kind"] == "ConfigMap"], "ConfigMap is generated by DEPLOY.md, not committed"
    assert not list(DEPLOY.glob("*pronounce*")) and not list(DEPLOY.glob("*configmap*"))


def test_deployment_shape(deployment):
    spec = deployment["spec"]
    assert spec["replicas"] == 1
    assert spec["strategy"]["type"] == "Recreate"
    pod = spec["template"]["spec"]
    assert pod["securityContext"]["runAsNonRoot"] is True
    assert pod["securityContext"]["runAsUser"] == 1000
    assert pod["securityContext"]["fsGroup"] == 1000


def test_deployment_resources_and_security(container):
    res = container["resources"]
    assert res["requests"] == {"cpu": "500m", "memory": "1Gi"}
    assert res["limits"] == {"cpu": "1500m", "memory": "2Gi"}
    sc = container["securityContext"]
    assert sc["allowPrivilegeEscalation"] is False
    assert sc["readOnlyRootFilesystem"] is True
    assert container["imagePullPolicy"] == "IfNotPresent"
    image = container["image"]
    assert image.startswith("kick-tts:") and not image.endswith(":latest")


def test_deployment_env(container):
    env = _env(container)
    for name in ("OMP_NUM_THREADS", "MKL_NUM_THREADS", "TORCH_NUM_THREADS"):
        assert env.get(name) == "2", f"{name} must be the string \"2\""
    assert env["HF_HUB_OFFLINE"] == "1"
    assert env["PRONOUNCE_PATH"] == "/config/pronounce.yaml"
    assert any(e.get("secretRef", {}).get("name") == "kick-tts-secrets" for e in container["envFrom"])


def test_deployment_volumes_and_cache_env(deployment, container):
    pod = deployment["spec"]["template"]["spec"]
    mounts = {m["name"]: m for m in container["volumeMounts"]}
    volumes = {v["name"]: v for v in pod["volumes"]}

    assert mounts["cache"]["mountPath"] == "/cache"
    assert _env(container)["XDG_CACHE_HOME"] == "/cache" == mounts["cache"]["mountPath"]
    assert volumes["cache"]["persistentVolumeClaim"]["claimName"] == _one("pvc.yaml", "PersistentVolumeClaim")["metadata"]["name"]

    assert mounts["config"]["mountPath"] == "/config"
    assert volumes["config"]["configMap"]["name"] == "kick-tts-pronounce"

    # read-only root filesystem needs a writable /tmp
    assert mounts["tmp"]["mountPath"] == "/tmp"
    assert "emptyDir" in volumes["tmp"]


def test_deployment_probes(container):
    port = next(p for p in container["ports"] if p["name"] == "http")
    assert port["containerPort"] == 8000

    startup = container["startupProbe"]
    assert startup["httpGet"]["path"] == "/readyz"
    assert startup["periodSeconds"] == 5
    assert startup["failureThreshold"] == 60
    assert container["readinessProbe"]["httpGet"]["path"] == "/readyz"
    assert container["livenessProbe"]["httpGet"]["path"] == "/healthz"
    for probe in (startup, container["readinessProbe"], container["livenessProbe"]):
        assert probe["httpGet"]["port"] == "http"


