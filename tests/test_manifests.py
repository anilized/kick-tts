_SECRET_PATTERNS = [
    re.compile(r"sk-ant-"),
    re.compile(r"\bsk-[A-Za-z0-9]{20,}"),
    re.compile(r"\b[0-9a-fA-F]{32,}\b"),  # hex blobs (sha256, tokens)
    # long base64 / token-looking strings that mix letters and digits
    re.compile(r"(?=[A-Za-z0-9+/=_-]*\d)(?=[A-Za-z0-9+/=_-]*[A-Za-z])[A-Za-z0-9+/=_-]{32,}"),
]


@pytest.mark.parametrize(
    "path",
    [*sorted(DEPLOY.glob("*.yaml")), ROOT / "Dockerfile", ROOT / "docs" / "DEPLOY.md"],
    ids=lambda p: p.name,
)
def test_no_real_looking_secrets(path: Path):
    text = path.read_text(encoding="utf-8")
    for pattern in _SECRET_PATTERNS:
        match = pattern.search(text)
        assert match is None, f"{path.name}: looks like a credential: {match.group(0)[:12]}..."


def test_secret_scan_patterns_catch_real_looking_values():
    # guard against the scanner silently matching nothing
    samples = ["sk-ant-api03-abcdef", "0123456789abcdef0123456789abcdef", "Zm9vYmFyMTIzNDU2Nzg5MGFiY2RlZmdoaWprbG1ub3A="]
    for sample in samples:
        assert any(p.search(sample) for p in _SECRET_PATTERNS), sample


def test_deploy_doc_covers_required_steps():
    doc = (ROOT / "docs" / "DEPLOY.md").read_text(encoding="utf-8")
    for needle in (
        "fetch_weights.py --revision <sha> --out weights --write-lock",
        "docker build --build-arg EMA_REVISION=<sha> -t kick-tts:<tag> .",
        "docker save kick-tts:<tag> | sudo k3s ctr images import -",
        "kubectl create configmap kick-tts-pronounce --from-file=pronounce.yaml=app/reader/pronounce.yaml -n streaming --dry-run=client -o yaml | kubectl apply -f -",
        "kubectl get prometheus -n monitoring -o yaml | grep -A5 serviceMonitorSelector",
        "kubectl get certificate -n streaming",
        "https://anildev.io/tts/healthz",
        "503",
        "torch",
        "2.14.1",
        "ema-lightning",
        "rollout restart",
        "rollout undo",
        "VmRSS",
        "kubectl apply -n streaming -f deploy/cronjob.yaml",
        "kubectl set image cronjob/kick-tts-subscribe",
    ):
        assert needle in doc, needle
    # apply order: pvc, configmap, secret, deployment, service, ingress, servicemonitor, cronjob
    # (the ConfigMap is created by a pipe command shown just before this block, so it is not in the list)
    order = [
        "-f deploy/pvc.yaml", "-f deploy/secret.local.yaml", "-f deploy/deployment.yaml",
        "-f deploy/service.yaml", "-f deploy/ingress.yaml", "-f deploy/servicemonitor.yaml",
        "-f deploy/cronjob.yaml",
    ]
    apply_section = doc.split("## 4. Apply", 1)[1].split("### ServiceMonitor selector", 1)[0]
    positions = [apply_section.index(item) for item in order]
    assert positions == sorted(positions)
